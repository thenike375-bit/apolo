type Dict = typeof en;

export const dicts = { en };

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: Dict }>({
  lang: "en",
  setLang: () => {},
  t: en,
});

/** English-only app; the provider keeps the `t` dictionary API. */
export function I18nProvider({ children }: { children: ReactNode }) {
  return <Ctx.Provider value={{ lang: "en", setLang: () => {}, t: en }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
